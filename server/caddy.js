// Caddy chạy ở container riêng `gen-chibi-edge` (docker-compose.edge.yml, P2): Caddyfile gốc edge/Caddyfile có khối global
// (admin unix//edge/run/caddy-admin.sock, http_port 8080, https_port 8443) + `import /edge/sites.caddy`. Tệp sites.caddy do app sinh ở đây:
//   - chỉ từ dữ liệu ĐÃ KIỂM: tên miền theo regex hostname RFC 1123 (≤ 253, nhãn ≤ 63, không wildcard, không IP), nonce hex — KHÔNG ghép chuỗi tự do
//   - http://<tên>: /.well-known/gen-chibi-check/<nonce> trả nonce (bậc kiểm cổng A3), còn lại chuyển https (thử thách ACME HTTP-01 Caddy luôn tự xử lý trước mọi route)
//   - https://<tên>: reverse_proxy app:7480 (service `app` của compose; bản native không có đường A) + xoá header IP do client gửi
//     + X-GC-Edge = bí mật đọc LÚC CHẠY bằng placeholder {file./edge/edge-secret} (Caddy ≥ 2.8, replacer.go fileReplacementProvider — kiểm 2026-10-20):
//     bí mật không nằm trong sites.caddy / config JSON; đổi bí mật không cần reload. Thiếu tệp → header rỗng → app không coi là edge (an toàn)
// Nạp lại: POST /load (Content-Type: text/caddyfile) qua unix socket admin, thân = Caddyfile GỐC ĐẦY ĐỦ (có khối admin) → cấu hình mới giữ admin (CNS-194).
// Chứng chỉ: Caddy tự xin + tự thử lại (staging khi lỗi — CNS-188); app chỉ ĐỌC tình trạng qua bắt tay TLS, không bao giờ xin lại.
'use strict';
const fs = require('fs');
const net = require('net');
const tls = require('tls');
const http = require('http');
const path = require('path');

// RFC 1123: nhãn 1–63 [a-z0-9-], không bắt đầu / kết thúc bằng '-'; ≥ 2 nhãn; nhãn cuối (TLD) bắt đầu bằng chữ (loại IPv4); tổng ≤ 253
const LABEL = '[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?';
const HOST_RE = new RegExp('^(?=.{1,253}$)(?:' + LABEL + '\\.)+[a-z](?:[a-z0-9-]{0,61}[a-z0-9])?$');
const LOCAL_SUFFIX = /(^|\.)(localhost|local|internal|invalid|arpa|onion)$/;
const NONCE_RE = /^[a-f0-9]{32}$/;
const UPSTREAM = 'app:7480';                         // service `app`, cổng trong container cố định (docker-compose.yml)
const SECRET_PLACEHOLDER = '{file./edge/edge-secret}';   // đường dẫn PHÍA CADDY (volume ./edge → /edge)

// tên miền hợp lệ → dạng chuẩn (chữ thường); không hợp lệ → ''
function validDomain(d) {
  if (typeof d !== 'string') return '';
  const s = d.toLowerCase();   // regex neo hai đầu (JS: `$` không khớp trước "\n" khi không có cờ m) — khoảng trắng / xuống dòng / "}" đều rơi
  if (!HOST_RE.test(s) || net.isIP(s) || LOCAL_SUFFIX.test(s)) return '';
  return s;
}

// nội dung sites.caddy — sites: [{ domain, nonce }] (đã kiểm lại ở đây: dữ liệu xấu → ném lỗi, không bao giờ ghi)
function sitesFile(sites) {
  const out = ['# gen-chibi — generated by the app (System › Go online). Do not edit: the next change overwrites this file.', '# © 2026 Gen Labs — All rights reserved.'];
  (sites || []).forEach(x => {
    const d = validDomain(x && x.domain);
    if (!d || d !== x.domain) throw Object.assign(new Error('caddy: invalid domain'), { code: 400 });
    if (!NONCE_RE.test(String(x.nonce || ''))) throw Object.assign(new Error('caddy: invalid nonce'), { code: 400 });
    out.push(
      'http://' + d + ' {',
      '\thandle /.well-known/gen-chibi-check/' + x.nonce + ' {',
      '\t\trespond "' + x.nonce + '" 200',
      '\t}',
      '\thandle {',
      '\t\tredir https://' + d + '{uri} 308',
      '\t}',
      '}',
      'https://' + d + ' {',
      '\treverse_proxy ' + UPSTREAM + ' {',
      '\t\theader_up -Cf-Connecting-Ip',
      '\t\theader_up -X-Real-Ip',
      '\t\theader_up -True-Client-Ip',
      '\t\theader_up X-GC-Edge ' + SECRET_PLACEHOLDER,
      '\t}',
      '}');
  });
  return out.join('\n') + '\n';
}

function writeAtomic(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = file + '.tmp';
  fs.writeFileSync(tmp, text, { mode: 0o600 });
  fs.chmodSync(tmp, 0o600);
  fs.renameSync(tmp, file);
}

// gọi admin API qua unix socket: { status, body }
function adminCall(socketPath, method, p, { body, type, timeoutMs = 15000 } = {}) {
  return new Promise((resolve, reject) => {
    const data = body == null ? null : Buffer.from(body);
    const req = http.request({ socketPath, path: p, method, timeout: timeoutMs, headers: Object.assign({ Host: 'localhost' }, data ? { 'Content-Type': type || 'application/json', 'Content-Length': data.length } : {}) }, res => {
      const chunks = []; let n = 0;
      res.on('data', c => { n += c.length; if (n <= 256 * 1024) chunks.push(c); });
      res.on('end', () => resolve({ status: res.statusCode, body: Buffer.concat(chunks).toString('utf8') }));
    });
    req.on('timeout', () => req.destroy(Object.assign(new Error('caddy admin timeout'), { code: 'ETIMEDOUT' })));
    req.on('error', reject);
    if (data) req.write(data);
    req.end();
  });
}

// thông tin chứng chỉ ở <ip>:443 với SNI = tên miền. CHỈ ĐỌC chứng chỉ rồi đóng (không gửi byte dữ liệu nào): bắt tay không chặn chứng chỉ chưa tin
// để còn nhận ra bản staging / tự ký và báo đúng tiến độ; kết luận "đạt" dựa trên s.authorized (chuỗi tin cậy hệ thống) + tên khớp
function tlsInfo(domain, ip, { port = 443, timeoutMs = 8000 } = {}) {
  return new Promise(resolve => {
    let done = false;
    const end = v => { if (!done) { done = true; try { s.destroy(); } catch (e) { /* đã đóng */ } resolve(v); } };
    const s = tls.connect({ host: ip, port, servername: domain, rejectUnauthorized: false, ALPNProtocols: ['http/1.1'] }, () => {
      const c = s.getPeerCertificate() || {};
      const issuer = c.issuer ? [c.issuer.O, c.issuer.CN].filter(Boolean).join(' · ') : '';
      const sans = String(c.subjectaltname || '').split(',').map(x => x.trim().replace(/^DNS:/, '').toLowerCase());
      const matches = sans.includes(domain) || sans.some(x => x.startsWith('*.') && domain.endsWith(x.slice(1)) && domain.split('.').length === x.split('.').length);
      end({ ok: true, authorized: s.authorized === true, error: s.authorizationError ? String(s.authorizationError) : '', issuer, staging: /staging|fake le|pretend|ersatz/i.test(issuer), matches, validTo: c.valid_to ? new Date(c.valid_to).toISOString() : '' });
    });
    s.setTimeout(timeoutMs, () => end({ ok: false, error: 'timeout' }));
    s.on('error', e => end({ ok: false, error: e.code || e.message }));
  });
}

function createCaddy({ edgeDir, adminCallFn = adminCall }) {
  const files = {
    root: path.join(edgeDir, 'Caddyfile'),
    sites: path.join(edgeDir, 'sites.caddy'),
    enabled: path.join(edgeDir, 'caddy.enabled'),          // dấu do lệnh host `genchibi online --caddy` ghi (P2): edge đã publish 80/443
    socket: path.join(edgeDir, 'run', 'caddy-admin.sock')
  };
  const enabled = () => fs.existsSync(files.enabled);
  async function adminUp() {
    try { const r = await adminCallFn(files.socket, 'GET', '/config/', { timeoutMs: 3000 }); return r.status === 200; } catch (e) { return false; }
  }
  // Caddyfile gốc phải có admin unix socket + import sites — thiếu admin thì /load sẽ đưa admin về localhost:2019 trong container (mất điều khiển) → từ chối
  function rootText() {
    let t = '';
    try { t = fs.readFileSync(files.root, 'utf8'); } catch (e) { throw Object.assign(new Error('caddy: edge/Caddyfile missing'), { code: 'ROOT_MISSING' }); }
    if (!/^\s*admin\s+unix\/\/\S+/m.test(t)) throw Object.assign(new Error('caddy: edge/Caddyfile has no "admin unix//…" line'), { code: 'ROOT_NO_ADMIN' });
    if (!/^\s*import\s+\/edge\/sites\.caddy\s*$/m.test(t)) throw Object.assign(new Error('caddy: edge/Caddyfile does not import /edge/sites.caddy'), { code: 'ROOT_NO_IMPORT' });
    return t;
  }
  function writeSites(sites) { const text = sitesFile(sites); writeAtomic(files.sites, text); return text; }
  // POST /load với Caddyfile gốc đầy đủ; lỗi adapt / nạp → ném kèm câu gốc của Caddy (cắt ngắn)
  async function reload() {
    const text = rootText();
    const r = await adminCallFn(files.socket, 'POST', '/load', { body: text, type: 'text/caddyfile' });
    if (r.status !== 200) {
      let msg = r.body; try { const j = JSON.parse(r.body); if (j && typeof j.error === 'string') msg = j.error; } catch (e) { /* không phải JSON */ }
      throw Object.assign(new Error(String(msg || '').replace(/\s+/g, ' ').slice(0, 300)), { code: 'LOAD_' + r.status });
    }
    return true;
  }
  return { files, enabled, adminUp, writeSites, reload, rootText, tlsInfo };
}

module.exports = { createCaddy, validDomain, sitesFile, adminCall, tlsInfo, HOST_RE, UPSTREAM, SECRET_PLACEHOLDER };
